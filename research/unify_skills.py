def strip_front(text):
    if text.startswith("---"):
        m = re.match(r"^---\n.*?\n---\n", text, re.S)
        if m:
            return text[m.end():]
    return text


def sections(text):
    """Return list of (level, heading, body) for ## and ### headings."""
    lines = text.splitlines()
    out, cur_lvl, cur_head, buf = [], None, None, []
    for line in lines:
        m = re.match(r"^(#{2,3})\s+(.+?)\s*$", line)
        if m:
            if cur_head:
                out.append((cur_lvl, cur_head, "\n".join(buf).strip()))
            cur_lvl, cur_head, buf = len(m.group(1)), m.group(2).strip(), []
        elif cur_head:
            buf.append(line)
    if cur_head:
        out.append((cur_lvl, cur_head, "\n".join(buf).strip()))
    return out


def classify(heading):
    h = heading.lower()
    if any(k in h for k in ("step-by-step", "quick win", "autonomous testing", "discovery checklist",
                            "deeper checklist", "methodology")):
        return "method"
    if any(k in h for k in ("signal", "attack surface", "where to look", "where it pays",
                            "tech stack", "in-scope", "crown jewel")):
        return "signals"
    if any(k in h for k in ("bypass", "technique", "payload", "vector famil", "dom source",
                            "dom clobber", "waf", "operator-level", "root cause")):
        return "techniques"
    if any(k in h for k in ("validation", "gate 0", "reporting bar", "oob", "confirmation")):
        return "validation"
    if any(k in h for k in ("chain", "related skill", "escalat")):
        return "chains"
    if any(k in h for k in ("tool", "wordlist", "nuclei", "grep pattern")):
        return "tools"
    if any(k in h for k in ("case stud", "real impact", "techniques from real reports")):
        return "cases"
    if any(k in h for k in ("source", "related", "query the corpus")):
        return "sources"
    return "other"


def dedup_blocks(blocks):
    seen, out = set(), []
    for b in blocks:
        key = hashlib.sha1(re.sub(r"\s+", " ", b).strip().lower().encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        out.append(b.strip())
    return out


def canonical(name):
    n = name
    if n.startswith("hackerone-"):
        n = n[len("hackerone-"):]
    if n.startswith("hunt-") and n not in ALIASES:
        n = n[len("hunt-"):]
    return ALIASES.get(n, n)


def collect_sources():
    groups = {}
    for src, root in SOURCES.items():
        for f in glob.glob(root + "/**/SKILL.md", recursive=True):
            name = os.path.basename(os.path.dirname(f))
            slug = canonical(name)
            text = open(f, errors="ignore").read()
            groups.setdefault(slug, []).append({
                "src": src, "name": name, "path": f, "text": text,
                "body": strip_front(text), "sections": sections(strip_front(text)),
            })
    return groups


def title_for(slug):
    if slug in CLASS_META:
        return CLASS_META[slug]["name"]
    if slug in PHASE:
        return PHASE[slug][0]
    if slug in EXTRA:
        return EXTRA[slug][0]
    return slug.replace("-", " ").title()


def description_for(slug, sources):
    if slug in CLASS_META:
        base = CLASS_META[slug]["trigger"].rstrip(".")
    elif slug in PHASE:
        base = PHASE[slug][1].rstrip(".")
    elif slug in EXTRA:
        base = EXTRA[slug][1].rstrip(".")
    else:
        base = f"Unified methodology for {title_for(slug).lower()}."
    repos = ", ".join(sorted({s["src"] for s in sources}))
    corpus = " Plus evidence from all 15,259 disclosed HackerOne reports." if slug in CLASS_META else ""
    full = f"{base}. Unified from {len(sources)} upstream skills ({repos}).{corpus} For authorized security testing only."
    return full.replace("\n", " ")


def build_skill(slug, sources):
    d = os.path.join(SKILLS, f"bbhunt-{slug}")
    os.makedirs(os.path.join(d, "references"), exist_ok=True)

    buckets = {"method": [], "signals": [], "techniques": [], "validation": [],
               "chains": [], "tools": [], "cases": [], "sources": [], "other": []}
    for s in sources:
        for lvl, head, body in s["sections"]:
            if not body or len(body) < 12:
                continue
            buckets[classify(head)].append(f"### {head}\n\n{body}")

    # Preserve full upstream originals.
    for s in sources:
        with open(os.path.join(d, "references", f"upstream-{s['src']}-{s['name']}.md"), "w") as f:
            f.write(f"# Upstream source: {s['name']} ({s['src']})\n\nOriginal path: `{s['path']}`\n\n"
                    "---\n\n" + s["text"])

    unified = ["# Unified upstream methodology\n",
               "Collected from every contributing repository skill. Deduplicated by content hash; "
               "full originals are preserved in `references/upstream-*.md`.\n"]
    labels = {
        "method": "Discovery and hunting method", "signals": "Signals and surfaces",
        "techniques": "Techniques, payloads and bypasses", "validation": "Validation and proof",
        "chains": "Escalation and related chains", "tools": "Tools and wordlists",
        "cases": "Real-world examples", "sources": "Sources and related reading",
        "other": "Additional notes",
    }
    for key in ("method", "signals", "techniques", "validation", "chains", "tools", "cases", "sources", "other"):
        blocks = dedup_blocks(buckets[key])
        if blocks:
            unified += [f"## {labels[key]}\n", "\n\n".join(blocks), ""]
    with open(os.path.join(d, "references", "unified-method.md"), "w") as f:
        f.write("\n".join(unified))

    # SKILL.md — unified view, concise but complete, with pointers to full detail.
    desc = description_for(slug, sources)
    is_class = slug in CLASS_META
    parts = [
        "---\n", f"name: bbhunt-{slug}\n", f"description: {json.dumps(desc)}\n",
        "agent_created: true\n", "---\n\n",
        f"# {title_for(slug)} — unified methodology\n\n",
        f"> **Unified skill.** Built from {len(sources)} upstream skills across "
        + ", ".join(sorted({s['src'] for s in sources}))
        + (" and the local HackerOne corpus." if is_class else ".")
        + " Full originals are in `references/upstream-*.md`; the deduplicated union is in "
          "`references/unified-method.md`.\n\n",
    ]
    if is_class:
        n = CLASS_META[slug]
        parts += [
            "## Corpus-backed method (this class)\n\n",
            "\n".join(f"{i+1}. {s}" for i, s in enumerate(n["steps"])) + "\n\n",
            "### Signals\n\n" + "\n".join(f"- {s}" for s in n["signals"]) + "\n\n",
            "### Kill criteria\n\n" + "\n".join(f"- {s}" for s in n["kill"]) + "\n\n",
            "### Escalation chains\n\n" + "\n".join(f"- {s}" for s in n["chains"]) + "\n\n",
            "### Veteran tip\n\n" + n["tip"] + "\n\n",
        ]
    parts += [
        "## Unified upstream methodology (deduplicated)\n\n",
    ]
    for key in ("method", "signals", "techniques", "validation", "chains", "tools"):
        blocks = dedup_blocks(buckets[key])
        if not blocks:
            continue
        parts += [f"### {labels[key]}\n\n"]
        # Keep SKILL.md lean: include up to 6 blocks, full set is in references.
        for b in blocks[:6]:
            parts.append(b[:1600] + "\n\n")
        if len(blocks) > 6:
            parts.append(f"_...and {len(blocks)-6} more sections in `references/unified-method.md`._\n\n")
    parts += [
        "## Source skills merged into this topic\n\n",
        "\n".join(f"- `{s['src']}` — `{s['name']}`" for s in sources) + "\n\n",
        "## References\n\n",
        "- `references/unified-method.md` — complete deduplicated union of all upstream sections\n",
        "- `references/upstream-*.md` — full original SKILL.md from each contributing repo\n",
    ]
    if is_class:
        parts.append("- `references/evidence.md` — corpus technique frequencies, parameters, case studies and payload bank\n")
    parts += [
        "- `bbhunt-methodology` — orchestrator, state machine and class router\n",
    ]
    skill_md = os.path.join(d, "SKILL.md")
    if slug in PRESERVE and os.path.exists(skill_md):
        # Keep the hand-authored orchestrator/phase SKILL.md intact; append a
        # short pointer to the newly merged upstream references.
        existing = open(skill_md).read()
        if "references/unified-method.md" not in existing:
            pointer = (
                "\n## Unified upstream methodology\n\n"
                f"All {len(sources)} contributing upstream skills from "
                + ", ".join(sorted({s['src'] for s in sources}))
                + " are merged and deduplicated in `references/unified-method.md`; "
                  "full originals are preserved as `references/upstream-*.md`.\n"
            )
            with open(skill_md, "w") as f:
                f.write(existing.rstrip() + "\n" + pointer)
    else:
        with open(skill_md, "w") as f:
            f.write("".join(parts))
    return len(sources)


